echo "Moodist (remvze) https://github.com/$REPO, commit \`$COMMIT\`, \`public/sounds/\`."
printf '\n## Supplied by the site owner (not from Moodist)\n\n- `myittar-poe.mp3`, `chant-of-metta.mp3`, `mahapatthana.mp3`: supplied by the site owner (already in the repo before this revamp, not from Moodist).\n\n## Files\n\n'
while IFS="$(printf '\t')" read -r i c p d t; do
  echo "- \`rec/$c/$i.mp3\`: Moodist (remvze) \`public/sounds/$p\`, upstream licence Pixabay Content License or CC0."
done < "$ROWS"
printf '\n## Dropped or substituted\n\n'
printf -- '- Spec "frogs" -> upstream `animals/frog.mp3` (no plural file). Spec "dogs" -> `animals/dog-barking.mp3`. Spec "sailboat", "train" etc. exist as named.\n'
printf -- '- Binaural wavs, `silence.wav` and brainwave/isochronic tones are not vendored (tones are synthesised; brainwave stays in the engine).\n'
if [ -s "$DROPS" ]; then
  while IFS="$(printf '\t')" read -r i c p r; do echo "- DROPPED \`$i\` (\`$p\`): $r."; done < "$DROPS"
else
  printf -- '- No file failed the objective checks (>= 1 s, silence fraction <= 0.9, source not clipped). A human listening pass is still owed.\n'
fi
} > "$REC/CREDITS.md"
echo "done"
