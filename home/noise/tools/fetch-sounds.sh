Generated by `home/noise/tools/fetch-sounds.sh`. Do not edit by hand.

## Licence finding (Pixabay Content License)

Read at https://pixabay.com/service/license-summary/ (full URL) on 2026-11-17. The summary says content may be used free, without attribution, and modified or adapted. It prohibits selling or distributing content on a standalone basis (content with no creative effort applied, substantially in its original form), commercial use of recognisable trademarks or logos, immoral, illegal, misleading or deceptive use, and using content as a trademark or business name. It does not mention audio or repositories specifically; the full Terms of Service are the binding text. Standalone redistribution is therefore NOT clearly permitted: the files below are re-encoded (lossy mp3 re-compression, resampled to 44.1 kHz, mostly downmixed to mono, metadata stripped; loudness gain is applied at playback via `trim`, not baked in), so they are not unaltered originals, though no creative edit is applied. They are served as parts of a mix player rather than as a download. The owner has accepted this risk (2026-11-17). Any sound whose origin cannot be supported is dropped.

Moodist itself is MIT-licensed code; its sounds are third-party (per upstream: Pixabay Content License or CC0). Moodist has no per-sound credits file, so per-file origin below is recorded as "Moodist (remvze), upstream licence Pixabay Content License or CC0".

## Source

