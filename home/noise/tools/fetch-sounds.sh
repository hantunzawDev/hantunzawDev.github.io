#!/bin/sh
# Vendor curated Moodist sounds into home/noise/rec. Needs curl, ffmpeg, ffprobe, python3.
# Usage: sh home/noise/tools/fetch-sounds.sh   (set MOODIST_COMMIT to pin a commit)
set -eu
PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
HERE=$(cd "$(dirname "$0")" && pwd)
REC="$HERE/../rec"
WORK="${TMPDIR:-/tmp}/noise-src"
mkdir -p "$WORK"
REPO=remvze/moodist
STEREO=" light-rain heavy-rain rain-on-window rain-on-leaves waves river waterfall jungle "  # joint-stereo 80k
TONAL=" birds crickets seagulls whale singing-bowl wind-chimes typewriter "  # mono 64k; rest of the mono files 48k (size budget)

COMMIT="${MOODIST_COMMIT:-}"
if [ -z "$COMMIT" ] && [ -s "$REC/manifest.json" ]; then
  COMMIT=$(python3 -I -c 'import json,sys;print(json.load(open(sys.argv[1]))["commit"])' "$REC/manifest.json")
fi
if [ -z "$COMMIT" ]; then
  COMMIT=$(curl -fsSL "https://api.github.com/repos/$REPO/commits/main" |
    python3 -I -c 'import json,sys;print(json.load(sys.stdin)["sha"])')
fi
echo "moodist commit $COMMIT"

ROWS="$WORK/rows.tsv"; DROPS="$WORK/drops.txt"; : > "$ROWS"; : > "$DROPS"
MEAS="$REC/measurements.tsv"
printf 'id\tdur_s\tlufs\ttrue_peak_dbtp\tsilence_frac\tkb\ttrim\n' > "$MEAS"

while IFS="$(printf '\t')" read -r id cat path; do
  [ -n "$id" ] || continue
  src="$WORK/$COMMIT-$(echo "$path" | tr / _)"
  [ -s "$src" ] || { curl -fsSL "https://raw.githubusercontent.com/$REPO/$COMMIT/public/sounds/$path" -o "$src.part" && mv "$src.part" "$src"; }
  mkdir -p "$REC/$cat"
  out="$REC/$cat/$id.mp3"
  case "$STEREO" in
    *" $id "*) enc="-ac 2 -b:a 80k -joint_stereo 1" ;;
    *) case "$TONAL" in *" $id "*) enc="-ac 1 -b:a 64k" ;; *) enc="-ac 1 -b:a 48k" ;; esac ;;
  esac
  clip=$(ffmpeg -nostdin -nostats -i "$src" -af astats=measure_overall=Peak_level+Peak_count+Number_of_samples:measure_perchannel=none -f null - 2>&1 |
    awk '/Peak level dB/ {p=$NF} /Peak count/ {c=$NF} /Number of samples/ {n=$NF} END{print (p>=-0.1 && n>0 && c/n>0.0005) ? "yes" : "no"}')
  ffmpeg -nostdin -v error -y -i "$src" -vn -ar 44100 -c:a libmp3lame $enc -map_metadata -1 "$out"
  dur=$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$out")
  ebu=$(ffmpeg -nostdin -nostats -i "$out" -af ebur128=peak=true -f null - 2>&1)
  lufs=$(printf '%s\n' "$ebu" | awk '/^ *I:/ {v=$2} END{print v}')
  tp=$(printf '%s\n' "$ebu" | awk '/True peak:/ {f=1} f && /Peak:/ {v=$2} END{print v}')
  sil=$(ffmpeg -nostdin -nostats -i "$out" -af silencedetect=n=-50dB:d=0.5 -f null - 2>&1 |
    awk -v d="$dur" '/silence_duration/ {s+=$NF} END{printf "%.3f", (d>0? s/d : 0)}')
  kb=$(( $(wc -c < "$out") / 1024 ))
  reason=""
  awk -v d="$dur" 'BEGIN{exit !(d<1)}' && reason="shorter than 1 s"
  awk -v s="$sil" 'BEGIN{exit !(s>0.9)}' && reason="mostly silent ($sil)"
  [ "$lufs" = "-inf" ] && reason="digital silence"
  [ "$clip" = yes ] && reason="source is clipped (many full-scale samples)"
  if [ -n "$reason" ]; then
    rm -f "$out"; echo "DROP $id: $reason"
    printf '%s\t%s\t%s\t%s\n' "$id" "$cat" "$path" "$reason" >> "$DROPS"
    continue
  fi
  trim=$(awk -v l="$lufs" -v p="$tp" 'BEGIN{t=10^((-23-l)/20); h=10^((-1-p)/20); if(t>h)t=h; if(t<0.2)t=0.2; if(t>6)t=6; printf "%.3f", t}')
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$id" "$dur" "$lufs" "$tp" "$sil" "$kb" "$trim" >> "$MEAS"
  printf '%s\t%s\t%s\t%s\t%s\n' "$id" "$cat" "$path" "$dur" "$trim" >> "$ROWS"
  echo "ok   $id dur=$dur lufs=$lufs tp=$tp sil=$sil trim=$trim"
done < "$HERE/sounds.tsv"

python3 -I - "$COMMIT" "$ROWS" "$REC/manifest.json" <<'PY'
import json, sys
commit, rows, out = sys.argv[1:4]
sounds = {}
for line in open(rows):
    i, c, p, d, t = line.rstrip("\n").split("\t")
    sounds[i] = {"category": c, "file": "rec/%s/%s.mp3" % (c, i), "dur": round(float(d), 2), "trim": float(t)}
json.dump({"commit": commit, "sounds": sounds}, open(out, "w"), indent=1)
open(out, "a").write("\n")
PY

{
cat <<'MD'
